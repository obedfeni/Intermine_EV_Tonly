export type TKey = keyof typeof translations.en
export function t(locale: Locale, key: TKey, vars?: Record<string,string|number>): string {
  let text = (translations[locale] as any)[key] ?? (translations.en as any)[key] ?? String(key)
  if (vars) Object.entries(vars).forEach(([k,v]) => { text = text.replace(`{${k}}`,String(v)) })
  return text
}
